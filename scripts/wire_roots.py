def has(n):   # a @Serializable class in package dev.jellystructure.shared.tv
    return re.search(r'@Serializable[^\n]*\n(?:\s*@[^\n]*\n)*\s*(?:data |sealed |open )?class ' + n + r'\b', src) is not None

print('// Generated by scripts/wire_roots.py (R319) — do not edit; edit the lists in the script.')
print('package dev.jellystructure.shared.wire\n')
print('import dev.jellystructure.shared.tv.*\n')
print('val WIRE_ROOTS: List<WireRoot> = listOf(')
for n in RESPONSES:
    if has(n): print(f'    WireRoot("{n}", WireDir.RESPONSE, {n}.serializer()),')
for n in REQUESTS:
    if has(n): print(f'    WireRoot("{n}", WireDir.REQUEST, {n}.serializer()),')
print(')')
