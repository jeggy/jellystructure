    'BrowseFacets', 'CardPlayState', 'CastHandoffResponse', 'Channel', 'DeviceStatusEnvelope', 'DiscoverDetail',
    'DiscoverEntry', 'DiscoverResponse', 'HomeFeed', 'LiveTvChannel', 'LiveTvGuideProgram', 'LiveTvStreamTicket',
