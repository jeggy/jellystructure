private val LOCALES: Map<String, Map<String, String>> = mapOf("en" to EN, "da" to DA, "fo" to FO)

// ─── Lookup function ──────────────────────────────────────────────────────────

fun t(key: String, lang: String, vars: Map<String, String> = emptyMap()): String {
    val table = LOCALES[lang] ?: LOCALES["en"]!!
    val fallback = LOCALES["en"]!!
    var result = table[key] ?: fallback[key] ?: key
    for ((k, v) in vars) result = result.replace("{$k}", v)
    return result
}
